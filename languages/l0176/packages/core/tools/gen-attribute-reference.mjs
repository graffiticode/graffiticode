// Generates spec.md's Attribute Reference from the registries, so it cannot
// drift from what the compiler actually accepts. The registries in
// question-types.ts say which words exist, what they emit and which types take
// them; tools/attribute-docs.mjs says what each means. A word in one and not the
// other fails the run. Build first: this reads dist/.
import { writeFileSync, readFileSync } from "node:fs";
import { validAttributes, memberFields } from "../dist/question-types.js";
import { lexicon } from "../dist/index.js";
import { GROUPS, DOCS } from "./attribute-docs.mjs";

const KEY_TO_TYPE = {
  MCQ: "mcq", SHORTTEXT: "shorttext", LONGTEXT: "longtext", PLAINTEXT: "plaintext",
  CLOZETEXT: "clozetext", CLOZEASSOCIATION: "clozeassociation",
  CLOZEDROPDOWN: "clozedropdown", CLOZEFORMULA: "clozeformula",
  CHOICEMATRIX: "choicematrix", ORDERLIST: "orderlist",
  CLASSIFICATION: "classification", BOWTIE: "bowtie", TOKEN_HIGHLIGHT: "token-highlight",
  TOKENHIGHLIGHT: "token-highlight",
};
// word -> emitted field, via the lexicon's NAME and the memberFields registry.
const fieldOf = new Map();
for (const [word, entry] of Object.entries(lexicon)) {
  const f = memberFields[entry.name]?.field;
  if (f) fieldOf.set(word, f);
}
const typesFor = (field) =>
  Object.entries(validAttributes)
    .filter(([, fields]) => fields.includes(field))
    .map(([k]) => KEY_TO_TYPE[k] || k.toLowerCase());
const questionFields = new Set(Object.values(validAttributes).flat());

// Coverage, both ways.
const problems = [];
for (const [word, field] of fieldOf) {
  const doc = DOCS[word];
  if (!doc) { problems.push(`${word}: in the registry, not in attribute-docs.mjs`); continue; }
  const isQuestion = questionFields.has(field);
  if (isQuestion && doc.group) problems.push(`${word}: a question attribute, so takes no group`);
  if (!isQuestion && !doc.group) problems.push(`${word}: nested, so needs a group`);
}
for (const [word, doc] of Object.entries(DOCS)) {
  if (!fieldOf.has(word) && !doc.extra) problems.push(`${word}: in attribute-docs.mjs, not in the registry`);
  if (doc.group && !GROUPS.some(([k]) => k === doc.group)) problems.push(`${word}: unknown group ${doc.group}`);
}
if (problems.length) {
  console.error(`gen-attribute-reference: ${problems.length} problems\n  ${problems.join("\n  ")}`);
  process.exit(1);
}

const words = Object.keys(DOCS).sort();
const groupOf = (w) => DOCS[w].group ?? "question";

const entry = (w) => {
  const doc = DOCS[w];
  const field = doc.emits ?? (fieldOf.has(w) ? `\`${fieldOf.get(w)}\`` : "—");
  const facts = [`Emits ${field}`, doc.value];
  if (groupOf(w) === "question") {
    const types = typesFor(fieldOf.get(w));
    facts.push(types.length === 13 ? "all types" : types.join(", "));
  }
  return `#### ${w}\n\n${facts.join(" · ")}\n\n${doc.text}\n`;
};

const sections = GROUPS.map(([key, title, intro]) => {
  const members = words.filter((w) => groupOf(w) === key);
  let out = `### ${title}\n\n${intro}\n`;
  if (key === "question") {
    const rows = members.map((w) => {
      const types = typesFor(fieldOf.get(w));
      return `| \`${w}\` | \`${fieldOf.get(w)}\` | ${types.length === 13 ? "all types" : types.join(", ")} |`;
    });
    out += `\n| keyword | Learnosity field | accepted by |\n|---|---|---|\n${rows.join("\n")}\n`;
  }
  return `${out}\n${members.map(entry).join("\n")}`;
});

const body = `## Attribute Reference

Every attribute the language accepts: the Learnosity field it emits, the value it
takes and where it goes. Generated by \`tools/gen-attribute-reference.mjs\` from
the registries in \`question-types.ts\` and the descriptions in
\`tools/attribute-docs.mjs\` — if a word is missing here it is missing from the
language, not from the documentation.

Every attribute is an arity-1 member, and an object is written as a member list,
so a question nests the way its JSON does:

\`\`\`
clozetext [
  stimulus "Complete the sentence."
  template "The {{response}} is the powerhouse of the cell."
  max-length 20
  validation [
    scoring-type "exactMatch"
    valid-response [score 1 value ["mitochondria"]]
  ]
]
\`\`\`

${sections.join("\n")}`;

const START = "<!-- BEGIN attribute-reference -->";
const END = "<!-- END attribute-reference -->";
const spec = readFileSync("spec/spec.md", "utf-8");
const block = `${START}\n${body}${END}`;
const next = spec.includes(START)
  ? spec.slice(0, spec.indexOf(START)) + block + spec.slice(spec.indexOf(END) + END.length)
  : spec.replace("## Program Examples", `${block}\n\n## Program Examples`);
writeFileSync("spec/spec.md", next);
const counts = GROUPS.map(([k, t]) => `${words.filter((w) => groupOf(w) === k).length} ${t}`);
console.log(`spec.md updated: ${counts.join(", ")}`);
