#!/usr/bin/env node
// AT-11 rollout step 7: the probe configs and the operator's commands for a production run
// (ISOLATE-01; plan: ~/.claude/plans/isolate-01-compiler-egress.md, step 7). Offline: it reads
// deploy.json and collect.json, writes the probe configs under deploy/egress-proxy/step7/at11/,
// and prints the gcloud commands for the operator to run. It runs nothing.
//
//   node scripts/at11/step7-jobs.js --admin <a proxy VM's address> [--image <digest ref>] [--write]
//
// --write   (re)writes probe-<class>.json and iam.json's canary. Without it, only the commands.
// --image   the built probe image by digest (…/at11-probe@sha256:…); a placeholder until built.
//
// The commands, in order:
//   1. the sentinel document at11/sentinel in Policy's and Broker's databases (IAM probe's
//      create and delete checks need one that exists);
//   2. the probe image (step7/Dockerfile.probe), whose configs are baked in at /config;
//   3. the control's project (step 0's graffiticode-isolate01) may pull it, so every job runs
//      one image digest;
//   4. every job: an IAM job per compiler account, a net job per deploy.json compiler on its
//      class, and the control job (step 0's, updated to this image);
//   5. the collector;
//   6. the teardown: the compiler jobs and the pull grant (the sentinels stay, for later runs).

import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { parseArgs } from "./lib.js";

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), "../..");
const DIR = "deploy/egress-proxy/step7/at11";
const PROJECT = "graffiticode";
const REGION = "us-central1";
const CONTROL_PROJECT = "graffiticode-isolate01";
const CONTROL_PROJECT_NUMBER_CMD = `gcloud projects describe ${CONTROL_PROJECT} --format='value(projectNumber)'`;
const IMAGE_TAG = `${REGION}-docker.pkg.dev/${PROJECT}/services/at11-probe:step7`;
const POLICY_HOST = "policy-sja7fatcta-uc.a.run.app";
// Step 0's run.app service in another project: a target for the classes that list Policy.
const OTHER_RUN_APP = "at11-own-default-o3flcplpsa-uc.a.run.app";
const EXTERNAL = new Set(["www.googleapis.com", "storage.googleapis.com"]);
const KIND = { "compilers-default": "default", "compilers-l0185": "open" };
// The control's canary resources, step 0's (decided 2026-10-20: reuse the prototype's).
export const CANARY = {
  secrets: [`projects/${CONTROL_PROJECT}/secrets/at11-canary-secret`],
  databases: [`projects/${CONTROL_PROJECT}/databases/at11-canary`],
  kmsKeys: [`projects/${CONTROL_PROJECT}/locations/${REGION}/keyRings/at11/cryptoKeys/canary-signing/cryptoKeyVersions/1`],
  impersonate: [`at11-canary-target@${CONTROL_PROJECT}.iam.gserviceaccount.com`],
  service: `projects/${CONTROL_PROJECT}/locations/${REGION}/services/at11-canary-svc`,
  project: `${CONTROL_PROJECT}-ctl`,
};

// The classes in use, from deploy.json: each class's subnet, listed and external hosts, and
// whether it lists Broker.
export function classesOf(services) {
  const classes = {};
  for (const [name, s] of Object.entries(services)) {
    const n = s.network;
    if (!n) continue;
    const c = classes[n.subnet] ??= { subnet: n.subnet, services: [], hosts: new Set() };
    c.services.push(name);
    for (const h of n.allow) c.hosts.add(h);
  }
  return Object.values(classes).map(c => ({ ...c, hosts: [...c.hosts].sort() }));
}

// One class's net probe config, from step 3's production L0176 config (which passed) with the
// class's own targets.
export function probeConfig(cls, base, { admin }) {
  const kind = KIND[cls.subnet] ?? "lang";
  const listed = cls.hosts.filter(h => !EXTERNAL.has(h) && !/^broker-/.test(h));
  const external = cls.hosts.filter(h => EXTERNAL.has(h));
  const listsPolicy = cls.hosts.includes(POLICY_HOST);
  const runApp = listsPolicy ? OTHER_RUN_APP : POLICY_HOST;
  const config = {
    ...base,
    $comment: `ISOLATE-01 step 7: the AT-11 network probe config for ${cls.subnet} (${cls.services.join(", ")}), generated by scripts/at11/step7-jobs.js from step 3's L0176 config.`,
    trailingDot: ["learnosity.com.", "items.learnosity.com.", `${runApp}.`],
    runApp: [runApp],
    fronting: { sni: "api.graffiticode.org", host: runApp },
    broker: { ...base.broker, relationship: cls.hosts.some(h => /^broker-/.test(h)) ? "invoker" : "unlisted" },
    admin: { address: admin, port: 9901 },
    kind,
    listed,
  };
  if (external.length) config.external = external; else delete config.external;
  if (kind === "open") {
    // A public name we run that this class doesn't list, so it goes through the open route.
    config.canary = "l0186.graffiticode.org";
    config.frontingOpen = { connect: "www.google.com", host: "example.com" };
  }
  return config;
}

const q = s => (/^[A-Za-z0-9_./:=@,+-]+$/.test(s) ? s : `'${s.replace(/'/g, "'\\''")}'`);
const cmd = (...argv) => argv.map(q).join(" ");

// The operator's commands, in order.
export function commands({ collect, classes, services, image }) {
  const out = [];
  const step = (title, ...lines) => out.push(`# ${title}`, ...lines, "");
  const classOf = Object.fromEntries(classes.flatMap(c => c.services.map(s => [s, c.subnet])));
  const lang = subject => subject.replace(/-run$/, "");
  const sa = subject => `${subject}@${PROJECT}.iam.gserviceaccount.com`;
  step("1. The sentinel at11/sentinel in Policy's and Broker's databases (once; it stays)",
    ...["policy", "broker"].map(db => `curl -sf -X PATCH -H "Authorization: Bearer $(gcloud auth print-access-token)" -H content-type:application/json ${q(`https://firestore.googleapis.com/v1/projects/${PROJECT}/databases/${db}/documents/at11/sentinel?currentDocument.exists=false`)} -d '{"fields":{"purpose":{"stringValue":"AT-11 IAM probe sentinel (ISOLATE-01 step 7); never read by a service"}}}'`));
  step("2. The probe image, from the repo root; note its digest",
    cmd("gcloud", "builds", "submit", `--project=${PROJECT}`, `--region=${REGION}`, "--config=deploy/egress-proxy/step7/probe.cloudbuild.yaml", "."),
    cmd("gcloud", "artifacts", "docker", "images", "describe", IMAGE_TAG, "--format=value(image_summary.digest)"));
  step(`3. ${CONTROL_PROJECT}'s Cloud Run agent may pull it (removed in 6)`,
    `N=$(${CONTROL_PROJECT_NUMBER_CMD})`,
    `gcloud artifacts repositories add-iam-policy-binding services --project=${PROJECT} --location=${REGION} --member=serviceAccount:service-$N@serverless-robot-prod.iam.gserviceaccount.com --role=roles/artifactregistry.reader --condition=None`);
  const common = [`--region=${REGION}`, `--image=${image}`, "--max-retries=0", "--task-timeout=600", "--execution-environment=gen2"];
  const jobs = [];
  jobs.push(cmd("gcloud", "run", "jobs", "deploy", collect.control, `--project=${CONTROL_PROJECT}`, ...common,
    `--service-account=at11-control@${CONTROL_PROJECT}.iam.gserviceaccount.com`,
    "--args=scripts/at11/iam.js,--role,control,--subject,at11-control,--config,/config/iam.json,--out,/tmp"));
  for (const c of collect.compilers) {
    jobs.push(cmd("gcloud", "run", "jobs", "deploy", c.iam, `--project=${PROJECT}`, ...common, `--service-account=${sa(c.subject)}`,
      `--args=scripts/at11/iam.js,--role,compiler,--subject,${c.subject},--config,/config/iam.json,--out,/tmp`));
    if (!c.net) continue;
    const subnet = classOf[lang(c.subject)];
    if (!subnet) throw new Error(`${c.subject} has a net job but no network class in deploy.json`);
    const ca = services[lang(c.subject)].network.ca;
    jobs.push(cmd("gcloud", "run", "jobs", "deploy", c.net, `--project=${PROJECT}`, ...common, `--service-account=${sa(c.subject)}`,
      "--network=compilers", `--subnet=${subnet}`, "--network-tags=compiler", "--vpc-egress=all-traffic",
      `--set-secrets=${ca.path}=${ca.secret}`, `--set-env-vars=NODE_EXTRA_CA_CERTS=${ca.path}`,
      `--args=scripts/at11/net.js,--class,${subnet},--subject,${c.subject},--config,/config/probe-${subnet}.json,--out,/tmp`));
  }
  step(`4. The jobs: the control (in ${CONTROL_PROJECT}), ${collect.compilers.length} IAM jobs and ${collect.compilers.filter(c => c.net).length} net jobs`, ...jobs);
  step("5. The collector (roles/logging.viewer and privateLogViewer in both projects); evidence in .gc-deploy/at11/<nonce>/",
    cmd("node", "scripts/at11/collect.js", "--config", `${DIR}/collect.json`));
  step("6. The teardown: the compiler jobs and the pull grant (the control job and the sentinels stay)",
    ...collect.compilers.flatMap(c => [c.iam, ...(c.net ? [c.net] : [])]).map(j => cmd("gcloud", "run", "jobs", "delete", j, `--project=${PROJECT}`, `--region=${REGION}`, "--quiet")),
    `gcloud artifacts repositories remove-iam-policy-binding services --project=${PROJECT} --location=${REGION} --member=serviceAccount:service-$N@serverless-robot-prod.iam.gserviceaccount.com --role=roles/artifactregistry.reader --condition=None`);
  return out.join("\n");
}

async function main() {
  const argv = process.argv.slice(2);
  const write = argv.includes("--write");
  const args = parseArgs(argv.filter(a => a !== "--write"), ["--admin", "--image"]);
  if (!/^10\.8\.0\.\d+$/.test(args["--admin"] ?? "")) throw new Error("usage: step7-jobs.js --admin <a proxy VM's address, 10.8.0.x> [--image <ref>] [--write]");
  const services = JSON.parse(await readFile(path.join(ROOT, "deploy.json"), "utf8")).services;
  const collect = JSON.parse(await readFile(path.join(ROOT, DIR, "collect.json"), "utf8"));
  const classes = classesOf(services);
  if (write) {
    const base = JSON.parse(await readFile(path.join(ROOT, "deploy/egress-proxy/step3/at11/probe-l0176.json"), "utf8"));
    for (const c of classes) await writeFile(path.join(ROOT, DIR, `probe-${c.subnet}.json`), `${JSON.stringify(probeConfig(c, base, { admin: args["--admin"] }), null, 2)}\n`);
    const iamPath = path.join(ROOT, DIR, "iam.json");
    const iam = JSON.parse(await readFile(iamPath, "utf8"));
    iam.canary = CANARY;
    await writeFile(iamPath, `${JSON.stringify(iam, null, 2)}\n`);
  }
  console.log(commands({ collect, classes, services, image: args["--image"] ?? `${IMAGE_TAG.replace(/:step7$/, "")}@sha256:<from step 2>` }));
}

if (import.meta.url === `file://${process.argv[1]}`) {
  main().catch(e => { console.error(e.message); process.exit(1); });
}
