#!/usr/bin/env node
// AT-11 rollout step 7: the collector's config for every compiler account (ISOLATE-01; plan:
// ~/.claude/plans/isolate-01-compiler-egress.md, step 7 and decision D6). The inventory is
// deploy.json's language services and every lNNNN-run / lNNNNr-run account in the project
// (compilerInventory). A legacy compiler outside deploy.json gets an IAM job and the D6
// network exception; every other compiler gets a net job and an IAM job.
//
//   node scripts/at11/step7-config.js --accounts <file> [--out deploy/egress-proxy/step7/at11/collect.json]
//
// <file>: one service-account email per line, from
//   gcloud iam service-accounts list --project=graffiticode --format='value(email)'
// (read-only; the operator runs it). Offline otherwise: it reads deploy.json and writes one file.

import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { parseArgs } from "./lib.js";
import { compilerInventory, compilerJobs, inventoryProblems } from "./collect.js";

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), "../..");
// The production compiler network's addresses (classes.json), for the collector's attribution.
const BLOCKED = { compilerSubnets: ["10.8.16.0/22", "10.8.20.0/22", "10.8.24.0/22", "10.8.28.0/22", "10.8.32.0/22"], proxySubnet: "10.8.0.0/27", loadBalancer: "10.8.0.2" };

// The step 7 collect.json for an inventory. Its network fields are the production compiler
// network's (step 1); the operator fills dnsLog from the step 1 records before a run.
export function step7Config(inventory) {
  const compilers = compilerJobs(inventory);
  const config = {
    $comment: "ISOLATE-01 rollout step 7: the AT-11 collector's config for every compiler account, generated by scripts/at11/step7-config.js. D6 entries are legacy compilers outside deploy.json: IAM-probed, network a recorded exception.",
    project: "graffiticode",
    region: "us-central1",
    control: "at11-iam-control",
    // Step 0's control and canary resources, reused (decided 2026-10-20).
    controlProject: "graffiticode-isolate01",
    compilers,
    excluded: [],
    dnsExfil: "at11.graffiticode.org",
    // The at11.graffiticode.org zone, and its query log, are step 0's.
    dnsLog: { filter: "resource.type=\"dns_query\" AND jsonPayload.queryName:\"at11.graffiticode.org\"", project: "graffiticode-isolate01" },
    blocked: BLOCKED,
    retries: { attempts: 8, waitMs: 30000 },
  };
  const problems = inventoryProblems(config, inventory);
  if (problems.length) throw new Error(`the generated config doesn't cover the inventory: ${problems.join("; ")}`);
  return config;
}

// The D6 wave's targeted run: the legacy compilers (network.json "legacy", now on the proxy) get
// net and IAM jobs; every other compiler is excluded, citing the run it passed.
export function d6Config(inventory, legacy, passedIn) {
  const base = step7Config(inventory);
  const lang = a => a.split("@")[0].replace(/-run$/, "");
  const config = {
    ...base,
    $comment: `ISOLATE-01 D6 wave: AT-11 for the legacy compilers now on the proxy, generated by scripts/at11/step7-config.js --d6. The others passed in run ${passedIn}.`,
    compilers: inventory.filter(i => legacy.has(lang(i.account))).map(i => ({ subject: `${lang(i.account)}-run`, net: `at11-net-${lang(i.account)}`, iam: `at11-iam-${lang(i.account)}` })),
    excluded: inventory.filter(i => !legacy.has(lang(i.account))).map(i => ({ subject: `${lang(i.account)}-run`, reason: `passed AT-11 run ${passedIn} (2026-10-20)` })),
  };
  const problems = inventoryProblems(config, inventory);
  if (problems.length) throw new Error(`the D6 config doesn't cover the inventory: ${problems.join("; ")}`);
  return config;
}

async function main() {
  const argv = process.argv.slice(2);
  if (argv.includes("--d6")) {
    const a = parseArgs(argv.filter(x => x !== "--d6"), ["--accounts", "--out", "--passed-in"]);
    const serviceAccounts = (await readFile(a["--accounts"], "utf8")).split("\n").map(s => s.trim()).filter(Boolean);
    const deployServices = JSON.parse(await readFile(path.join(ROOT, "deploy.json"), "utf8")).services;
    const network = JSON.parse(await readFile(path.join(ROOT, "deploy/egress-proxy/production/network.json"), "utf8"));
    const legacy = new Set(Object.entries(network.services).filter(([, v]) => v.legacy).map(([k]) => k));
    const config = d6Config(compilerInventory({ deployServices, serviceAccounts }), legacy, a["--passed-in"] ?? "b492fffa1316be33");
    const out = a["--out"] ?? path.join(ROOT, "deploy/egress-proxy/step7/at11/collect-d6.json");
    await writeFile(out, `${JSON.stringify(config, null, 2)}\n`);
    console.log(`${config.compilers.length} legacy compilers with net and IAM jobs, ${config.excluded.length} excluded; wrote ${out}`);
    return;
  }
  const args = parseArgs(argv, ["--accounts", "--out"]);
  if (!args["--accounts"]) throw new Error("usage: step7-config.js --accounts <file> [--out file]");
  const serviceAccounts = (await readFile(args["--accounts"], "utf8")).split("\n").map(s => s.trim()).filter(Boolean);
  const deployServices = JSON.parse(await readFile(path.join(ROOT, "deploy.json"), "utf8")).services;
  const inventory = compilerInventory({ deployServices, serviceAccounts });
  const config = step7Config(inventory);
  const out = args["--out"] ?? path.join(ROOT, "deploy/egress-proxy/step7/at11/collect.json");
  await writeFile(out, `${JSON.stringify(config, null, 2)}\n`);
  const d6 = config.compilers.filter(c => c.exception === "D6").length;
  console.log(`${inventory.length} compiler accounts: ${inventory.length - d6} with net and IAM jobs, ${d6} IAM-only under D6, none excluded; wrote ${out}`);
}

if (import.meta.url === `file://${process.argv[1]}`) {
  main().catch(e => { console.error(e.message); process.exit(1); });
}
